# Independent targets: no Stratonovich / Reimann double integral. The stationary
# Fokker-Planck density p(x) = sum_n c_n exp(i n x) of dphi/dtau = i - sin(phi) + xi obeys
# c_{n+1} + a_n c_n - c_{n-1} = 0 with a_n = 2 theta n + 2 j i (j = imaginary unit);
# its decaying solution is a continued fraction, and v = i + 2 pi Im c_1. The effective
# diffusion follows from homogenization:
# D = theta int (1 + chi')**2 p dx, with the periodic corrector chi solving
# (i - sin x) chi' + theta chi'' = v - (i - sin x); g_n = (chi')_n obeys
# g_{n+1} + b_n g_n - g_{n-1} = 0 (n >= 2), b_n = 2 j i - 2 theta n, g_1 (b_1 + g_2/g_1) = 1.
# All in extended precision, so exponentially small results keep their relative accuracy.
#
# The voltages are generated by the independent continued fraction (or the Bessel integral) at a
# known theta; the returned theta must recover it within the stated relative 1e-7 + 2e-9 |kappa|
# (kappa the exact sensitivity at that theta: the 1e-9 relative accuracy of mean_voltage, by which
# theta is defined, enters theta multiplied by |kappa|), and kappa must match the extended-precision
# derivative at the returned theta to 1e-6. The endpoint rule is defined with the voltages of
# mean_voltage at theta = 0.02 and 50, so the endpoint probes are built from mean_voltage.
# Every test case below is self-contained (its own imports and helper functions).

# --- test case 0 ---
# thermally activated phase slips below the critical current
import numpy as np


def _crown_case():
    import numpy as np
    import mpmath as _t_mp

    def _t_cf(i, theta, want_D=True):
        sgn = -1 if i < 0 else 1
        dps = 30 + int(1.8 / theta)
        with _t_mp.workdps(dps):
            a = _t_mp.mpf(abs(i))
            th = _t_mp.mpf(theta)
            N = 40 + int(1.3 * _t_mp.sqrt(2 * dps * 2.303 / th))
            J = _t_mp.mpc(0, 1)
            r = [_t_mp.mpc(0)] * (N + 2)
            dr = [_t_mp.mpc(0)] * (N + 2)
            for n in range(N, 0, -1):
                r[n] = 1 / (2 * th * n + 2 * J * a + r[n + 1])
                dr[n] = -r[n] ** 2 * (2 * J + dr[n + 1])
            v = a + _t_mp.im(r[1])
            dv = 1 + _t_mp.im(dr[1])
            if not want_D:
                return float(sgn * v), float(dv)
            c = [_t_mp.mpc(0)] * (N + 1)
            c[0] = 1 / (2 * _t_mp.pi)
            for n in range(1, N + 1):
                c[n] = r[n] * c[n - 1]
            s = [_t_mp.mpc(0)] * (N + 2)
            for n in range(N, 1, -1):
                s[n] = 1 / (-2 * th * n + 2 * J * a + s[n + 1])
            g = [_t_mp.mpc(0)] * (N + 1)
            g[1] = 1 / (2 * J * a - 2 * th + s[2])
            for n in range(2, N + 1):
                g[n] = s[n] * g[n - 1]
            h = np.array([_t_mp.conj(g[k]) for k in range(N, 0, -1)] + [_t_mp.mpc(1)] + g[1:], dtype=object)
            cf = np.array([_t_mp.conj(c[k]) for k in range(N, 0, -1)] + c, dtype=object)
            q = np.convolve(h, h)                       # Fourier coefficients of (1 + chi')**2, index -2N..2N
            tot = _t_mp.fsum(q[N:3 * N + 1][::-1] * cf)  # sum_m q_m c_{-m}, |m| <= N
            D = th * 2 * _t_mp.pi * _t_mp.re(tot)
            return float(sgn * v), float(dv), float(D)

    def _t_rel(x, y):
        return abs(x - y) / abs(y)

    def _t_kappa(i, theta):
        # d ln theta / d ln v from a central difference of the continued-fraction voltage
        # carried out entirely in extended precision (step 1e-15 theta, 60 + 1.8 / theta digits)
        dps = 60 + int(1.8 / theta)
        with _t_mp.workdps(dps):
            a, th = _t_mp.mpf(i), _t_mp.mpf(theta)
            N = 40 + int(1.3 * _t_mp.sqrt(2 * dps * 2.303 / th))
            J = _t_mp.mpc(0, 1)

            def v(t):
                r = _t_mp.mpc(0)
                for n in range(N, 0, -1):
                    r = 1 / (2 * t * n + 2 * J * a + r)
                return a + _t_mp.im(r)

            h = th * _t_mp.mpf(10) ** -15
            dlv = (_t_mp.log(v(th + h)) - _t_mp.log(v(th - h))) / (_t_mp.log(th + h) - _t_mp.log(th - h))
            return float(1 / dlv)

    def _t_check_temp(i, theta_true, v):
        # theta: relative 1e-7 + 2e-9 |kappa| with kappa the exact sensitivity at theta_true;
        # kappa: relative 1e-6 against the exact sensitivity at the returned theta
        out = noise_temperature(i, v)
        assert isinstance(out, tuple) and len(out) == 2 and all(isinstance(x, float) for x in out), out
        k_true = _t_kappa(i, theta_true)
        assert _t_rel(out[0], theta_true) < 1e-7 + 2e-9 * abs(k_true), (i, v, out, theta_true, k_true)
        k = _t_kappa(i, out[0])
        assert _t_rel(out[1], k) < 1e-6, (i, v, out, k)
        return out

    # (Arrhenius regime: kappa is small, close to theta / barrier, so the thermometer is sensitive)
    for _t_i, _t_th in ((0.5, 0.05), (0.2, 0.3), (0.9, 0.025), (0.05, 0.08)):
        _t_o = _t_check_temp(_t_i, _t_th, _t_cf(_t_i, _t_th, want_D=False)[0])
        assert 0.0 < _t_o[1] < 0.5


